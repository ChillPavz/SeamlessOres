"""The Matrix ores' fixed geology rule: which ore never forms in which host stone.

A refused pair is never built, and worldgen turns that ore into the host stone wherever the stone
swallows it, so no seam can appear. Fixed, not configurable: nothing registry-side may depend on
config. Seamless Ores' own vanilla-stone ores have a separate, optional, more lenient rule.

Host keys are HostStone.name() (namespace_path), ore keys OreKind.id(). The strict table plus a lore
rule for Create's four invented stones; the lenient alternative is kept in the maintainer notes only.
"""

CLASSES = {
    "LIME": ["blockus_limestone", "create_limestone"],
    "CALC": ["minecraft_calcite"],
    "ASPH": ["promenade_asphalt"],
    "MARB": ["blockus_marble"],
    "SCH": ["mythicupgrades_%s_schist" % g for g in ("aquamarine", "citrine", "peridot", "topaz")],
    "PLUT": ["wilderwild_gabbro", "blockus_bluestone"],
    "VOLC": ["minecraft_smooth_basalt", "create_scoria"],
}
ALL = list(CLASSES)


def _hosts(*classes):
    return [h for c in classes for h in CLASSES[c]]


_TIN = _hosts("CALC", "ASPH", "SCH", "PLUT", "VOLC")
_BERYL = _hosts("LIME", "CALC", "ASPH", "MARB", "PLUT", "VOLC")
_PERIDOT = _hosts("LIME", "CALC", "ASPH", "MARB", "SCH")
_CORUNDUM = _hosts("LIME", "CALC", "ASPH", "PLUT")
_PGM = _hosts("LIME", "CALC", "ASPH", "MARB", "SCH", "VOLC")

# ore -> hosts it is refused in
STRICT = {
    "coal": _hosts("CALC", "MARB", "SCH", "PLUT", "VOLC"),
    "emerald": _hosts("ASPH", "PLUT", "VOLC"),
    "lapis": _hosts("LIME", "ASPH", "SCH", "PLUT", "VOLC"),
    "diamond": _hosts(*ALL), "bort": _hosts(*ALL),
    "topaz": _hosts(*ALL), "silents_topaz": _hosts(*ALL),
    "zinc": _hosts("PLUT"), "galena": _hosts("PLUT"), "techreborn_lead": _hosts("PLUT"),
    "manganese": _hosts("PLUT"),
    "tin": _TIN, "energized_tin": _TIN, "techreborn_tin": _TIN,
    "aquamarine": _BERYL, "silents_aquamarine": _BERYL, "heliodor": _BERYL,
    "peridot": _PERIDOT, "silents_peridot": _PERIDOT,
    "techreborn_ruby": _CORUNDUM, "techreborn_sapphire": _CORUNDUM,
    "platinum": _PGM, "iridium": _PGM, "osmium": _PGM,
    "techreborn_uranium": _hosts("PLUT", "VOLC"),
}

# Invented ores and rock are never judged; nor is anything on an exempt host or in the Nether.
FICTION = set("redstone adamantite aquarium banglum carmot kyber midas_gold morkite mythril necoium "
              "nether_banglum orichalcum palladium prometheum quadrillum runite starrite stormyx "
              "unobtainium chaos prosperity".split())

# Create's four invented stones each keep only the ore Create ties them to, plus fiction (owner).
LORE = {"create_asurine": "zinc", "create_crimsite": "iron", "create_ochrum": "gold",
        "create_veridium": "copper"}


def refused(host, ore):
    if host in STRICT.get(ore, ()):
        return True
    keep = LORE.get(host)
    return keep is not None and ore != keep and ore not in FICTION


def java(hosts, ores):
    """MatrixGeology.java: the refused pairs among the given host names and ore ids, as a lookup."""
    rows = []
    for host in hosts:
        refused_here = [o for o in ores if refused(host, o)]
        if refused_here:
            rows.append('        put(table, "%s", %s);' % (host, ", ".join('"%s"' % o for o in refused_here)))
    return JAVA % "\n".join(rows)


JAVA = '''package com.chillpavz.seamlessores.matrix.content;

import java.util.HashMap;
import java.util.Map;
import java.util.Set;

/**
 * The fixed geology rule: the ores that never form in a host stone.
 *
 * <p>A refused pair is never registered, and worldgen turns that ore into the host stone wherever
 * the stone swallows it, so no seam can appear. Fixed, never configurable: the registered block set
 * must not depend on config.
 *
 * <p>GENERATED by tools/matrix/generate_matrix.py from tools/matrix/geology.py. Do not edit.
 */
public final class MatrixGeology {

    private MatrixGeology() {}

    /** Host name ({@link HostStone#name()}) -> refused ore ids ({@link OreKind#id()}). */
    private static final Map<String, Set<String>> REFUSED = build();

    private static Map<String, Set<String>> build() {
        final Map<String, Set<String>> table = new HashMap<>();
%s
        return Map.copyOf(table);
    }

    private static void put(Map<String, Set<String>> table, String host, String... ores) {
        table.put(host, Set.of(ores));
    }

    public static boolean refuses(String host, String ore) {
        return REFUSED.getOrDefault(host, Set.of()).contains(ore);
    }
}
'''
